const readStoredLocale = () => {
  try {
    return globalThis.localStorage?.getItem(STORAGE_KEY)
      || LEGACY_STORAGE_KEYS.map((key) => globalThis.localStorage?.getItem(key)).find(Boolean)
      || null;
  } catch { return null; }
};

let currentLocale = SUPPORTED.has(readStoredLocale()) ? readStoredLocale() : 'es';

export const getLocale = () => currentLocale;
export const getLocaleTag = () => currentLocale === 'en' ? 'en-US' : 'es-ES';

export function t(key, values = {}) {
  const template = MESSAGES[currentLocale]?.[key] ?? MESSAGES.es[key] ?? key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function tp(key, count, values = {}) {
  return t(`${key}.${Number(count) === 1 ? 'one' : 'other'}`, { count, ...values });
}

export function upperT(key, values = {}) {
  return t(key, values).toLocaleUpperCase(getLocaleTag());
}

export function applyTranslations(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  if (globalThis.document?.documentElement) globalThis.document.documentElement.lang = currentLocale;
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.setAttribute('title', t(node.dataset.i18nTitle));
  for (const node of root.querySelectorAll('[data-i18n-aria-label]')) node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  for (const node of root.querySelectorAll('[data-i18n-content]')) node.setAttribute('content', t(node.dataset.i18nContent));
  for (const node of root.querySelectorAll('[data-locale-select]')) node.value = currentLocale;
}

export function setLocale(locale, { persist = true, notify = true } = {}) {
  if (!SUPPORTED.has(locale)) return false;
  const changed = locale !== currentLocale;
  currentLocale = locale;
  if (persist) {
    try {
      globalThis.localStorage?.setItem(STORAGE_KEY, locale);
      for (const key of LEGACY_STORAGE_KEYS) globalThis.localStorage?.removeItem(key);
    } catch { /* almacenamiento no disponible */ }
  }
  applyTranslations();
  if (changed && notify && globalThis.document && typeof globalThis.CustomEvent === 'function') {
    globalThis.document.dispatchEvent(new CustomEvent('herdr-lcars:localechange', { detail: { locale } }));
  }
  return changed;
}

export function bindLocaleSelector(selectId, onChange) {
  applyTranslations();
  const select = globalThis.document?.getElementById(selectId);
  if (!select) return;
  select.value = currentLocale;
  select.addEventListener('change', () => setLocale(select.value));
  globalThis.document.addEventListener('herdr-lcars:localechange', () => {
    select.value = currentLocale;
    onChange?.(currentLocale);
  });
  globalThis.addEventListener?.('storage', (event) => {
    if ([STORAGE_KEY, ...LEGACY_STORAGE_KEYS].includes(event.key) && SUPPORTED.has(event.newValue)) {
      setLocale(event.newValue, { persist: false });
    }
  });
}

